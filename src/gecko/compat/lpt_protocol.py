def validate_lpt_protocol(version: str, problem: str) -> None:
    if version not in {LPT_V1, LPT_V4}:
        raise ValueError(f"Unsupported LPT construction protocol: {version}")
    if version == LPT_V1 and problem.upper() not in {"NC", "LC"}:
        raise ValueError("The frozen required-50x1 LPT-v1 protocol covers NC/LC only.")


def v1_diagnostics(diagnostics: Mapping[str, Any], *, problem: str, setting: str) -> dict[str, Any]:
    """Serialize the original field set while retaining every computed v1 value."""
    fields = V1_DIAGNOSTIC_FIELDS[f"{problem.lower()}_{setting}"]
    return {key: value for key, value in diagnostics.items() if key in fields}


V4_AGGREGATE_FIELDS = frozenset({"dirichlet_manipulation_audit", "benchmark_eligible"})
V4_RECORD_FIELDS = frozenset({
    "stream_key", "requested_temporal_profile", "effective_temporal_profile",
    "dirichlet_group_allocation_js_to_uniform_mean",
    "dirichlet_group_allocation_normalized_entropy_mean",
    "dirichlet_group_allocation_max_client_share_mean",
})


def v1_aggregate(payload: Mapping[str, Any]) -> dict[str, Any]:
    """Serialize computed records with the original frozen-v1 aggregate schema."""
    if payload.get("protocol_version") != LPT_V1:
        raise ValueError("The v1 aggregate serializer requires the LPT-v1 protocol")
    result = {key: value for key, value in payload.items() if key not in V4_AGGREGATE_FIELDS}
    result["records"] = [
        {key: value for key, value in record.items() if key not in V4_RECORD_FIELDS}
        for record in payload["records"]
    ]
    return result
